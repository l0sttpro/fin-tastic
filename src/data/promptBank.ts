/**
 * The prompt bank.
 *
 * Each prompt lists every accepted answer bucketed by how uncommon that
 * answer is. The source keeps six fine-grained bands, which are folded into
 * the game's five scoring tiers: the two commonest bands both pay Plankton
 * points. The tier a player lands in is therefore decided by their band.
 *
 * Band guide:
 *   band 0    - what the whole room says            -> Plankton
 *   band 1    - the second answer everyone thinks of -> Plankton
 *   band 2    - a genuine, slightly better answer    -> Reef Rookie
 *   band 3    - most players would never say this    -> Jawsome
 *   band 4    - specialist territory                 -> Fin-omenal
 *   band 5    - somebody had to know this to say it  -> Fin-tastic
 *
 * Within a prompt the bands are disjoint - an answer appears exactly once.
 *
 * Additional long-tail answers live in `data/extraAnswers.ts` and are appended
 * to these buckets before sanitising. Keeping them separate keeps this file
 * stable while the accepted-answer bank grows.
 */
function p(
  id: string,
  text: string,
  category: string,
  hint: string,
  bands: [string[], string[], string[], string[], string[], string[]],
  aliases: Record<string, string> = {},
): Prompt {
  return {
    id,
    text,
    category,
    hint,
    answers: {
      plankton: [...bands[0], ...bands[1]],
      'reef-rookie': bands[2],
      jawsome: bands[3],
      'fin-omenal': bands[4],
      fintastic: bands[5],
    },
    aliases,
  };
}

