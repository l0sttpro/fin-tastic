import type { Prompt } from '../game/types.ts';

/**
 * Extra prompts added to the original bank. They use the same six source
 * bands as `promptBank.ts`; the two commonest bands are folded into the
 * Plankton scoring tier when the bank is assembled.
 */
function p(
  id: string,
  text: string,
  category: string,
  hint: string,
  bands: [string[], string[], string[], string[], string[], string[]],
  aliases: Record<string, string> = {},
): Prompt {
  return {
    id,
    text,
    category,
    hint,
    answers: {
      plankton: [...bands[0], ...bands[1]],
      'reef-rookie': bands[2],
      jawsome: bands[3],
      'fin-omenal': bands[4],
      fintastic: bands[5],
    },
    aliases,
  };
}

